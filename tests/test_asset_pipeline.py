class TestPurgeCompleteness:
    def test_every_template_class_that_had_a_rule_survives(self):
        source = CSS_SOURCE.read_text(encoding="utf-8")
        minified = CSS_MIN.read_text(encoding="utf-8")
        source_classes = _class_tokens(source)
        min_classes = _class_tokens(minified)

        template_classes = set()
        for p in TEMPLATES_DIR.rglob("*.html"):
            text = p.read_text(encoding="utf-8")
            # Skip inline JS/CSS blocks (their `class="..."` strings are not
            # HTML class attributes) and Jinja expressions.
            text = re.sub(r"<script\b.*?</script>", " ", text, flags=re.S)
            text = re.sub(r"<style\b.*?</style>", " ", text, flags=re.S)
            text = re.sub(r"\{\{.*?\}\}|\{%.*?%\}", " ", text, flags=re.S)
            for m in re.finditer(r'class\s*=\s*"([^"]*)"', text):
                template_classes |= _class_tokens(m.group(1))

        def is_dynamic(c: str) -> bool:
            return any(c.startswith(p) for p in DYNAMIC_PREFIXES)

        # Classes purgecss treats as "used": template classes plus any class in
        # a dynamic (greedy-safelisted) family.
        used_classes = template_classes & source_classes
        effective_used = used_classes | {c for c in source_classes if is_dynamic(c)}

        purged = used_classes - min_classes
        if not purged:
            return

        # purgecss keeps a selector iff EVERY class in it is used. A purged
        # class is legitimate iff every source selector referencing it also
        # references some companion class that is itself unused.
        rules = _leaf_rules(source)
        unexplained = []
        for cls in sorted(purged):
            pattern = re.compile(r"(?<![\w-])" + re.escape(cls) + r"(?![\w-])")
            referencing = [sel for sel, _ in rules if pattern.search(sel)]
            fully_explained = True
            for sel in referencing:
                companions = (_class_tokens(sel) & source_classes) - {cls}
                if companions <= effective_used:
                    fully_explained = False
                    break
            if not fully_explained:
                unexplained.append((cls, referencing))
        assert not unexplained, (
            "classes used in templates were removed by the purge without a "
            "justifying unused companion class: "
            f"{[c for c, _ in unexplained]}. Regenerate with `npm run build` and "
            "check the purge safelist in scripts/build-assets.mjs."
        )
